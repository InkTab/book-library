export type Format = 'Hardcover' | 'Paperback'

export interface Book {
  id: string
  title: string
  author: string
  format: Format
  description: string
  /** Price in the shop's currency (see `formatPrice`). */
  price: number
  /** Cloth colour of the binding. */
  color: string
  /** Spine height on the shelf, in px. */
  height: number
  /** Spine thickness on the shelf, in px. */
  thickness: number
}

export interface Shelf {
  id: string
  label: string
  books: Book[]
}

const priceFormat = new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' })
export const formatPrice = (price: number) => priceFormat.format(price)

const H = 'Hardcover'
const P = 'Paperback'

type Row = [
  title: string,
  author: string,
  format: Format,
  price: number,
  color: string,
  height: number,
  thickness: number,
  description: string,
]

const toBooks = (shelfId: string, rows: Row[]): Book[] =>
  rows.map(([title, author, format, price, color, height, thickness, description], i) => ({
    id: `${shelfId}-${i}`,
    title,
    author,
    format,
    price,
    color,
    height,
    thickness,
    description,
  }))

